sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import roster, dbpf2

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

LUA_TYPE, LUA_GROUP = 0xCA63E2A3, 0x4A5E8EF6
NEWS_LUA_INSTANCE = 0x8BB3C100            # package signature 0BB3C100 (the old AFTERLIFE.lua range), high bit set as the pack does
LTEXT_TYPE = 0x2026960B
LTEXT_GROUP = 0x6A231EA4                  # advisor text group: every text@ string of the game and of CAM is in it
ADVICE_BASE = 0xBB3C2000                  # advice GUIDs: BB3C2000 + index of the character

# Query UIs of Cemetery_and_Church.dat: one new row per Afterlife value under the game's own "goofy stat" row.
# Each row has a label LTEXT and a value LTEXT (group EA5524EB, like the existing labels); the value LTEXT is a
# #afterlife_grid_var.FIELD# token, which the query expands when it is shown.
UI_TYPE, UI_GROUP = 0x00000000, 0x96A006B0
UI_TEXT_GROUP = 0xEA5524EB
UI_TEXT_BASE = 0xBB3C3000                 # label = base + 2n, value = base + 2n + 1
UI_ROWS = {
    0xCA8B9AA2: [  # Church (Weddings Per Week)
        ("Winners This Month", "WINNER_COUNT_THIS_CYCLE"),
        ("Souls in Heaven", "WINNER_POPULATION_HEAVEN"),
        ("Sinners Redeemed", "REDEEMED_TOTAL"),
        ("Heavenborn Population", "HEAVEN_NATIVE_TOTAL"),
    ],
    0xCA8B96C2: [  # Cemetery (Misplaced Coffins)
        ("Deaths This Month", "TOTAL_DEATHS_THIS_CYCLE"),
        ("I.M.P. Victims This Month", "IMP_KILLS_THIS_CYCLE"),
        ("Sinners This Month", "SINNER_COUNT_THIS_CYCLE"),
        ("Souls in Hell", "SINNER_POPULATION_HELL"),
        ("Hellborn Population", "HELL_NATIVE_TOTAL"),
    ],
}
UI_ROW_STEP = 20


def cpp_roster():
    out = ["\tconstexpr NewsCharacter kCharacters[] = {"]
    for k, name, role, src, species, iid, _ in roster.CHARACTERS:
        out.append(f'\t\t{{ "{k}", "{name}", "{role}", "{src}", "{species}", "text@{iid:08X}" }},')
    out.append("\t};\n")
    for ev, ks in roster.EVENTS:
        out.append(f"\tconstexpr const char* kEvent_{ev}[] = {{ " + ", ".join(f'"{k}"' for k in ks) + " };")
    out.append("\n\tconstexpr NewsEvent kEvents[] = {")
    for ev, _ in roster.EVENTS:
        out.append(f'\t\tEvent("{ev}", kEvent_{ev}),')
    out.append("\t};")
    return "\n".join(out) + "\n"


def write_cpp():
    p = os.path.join(ROOT, "src/afterlife/AfterlifeModel.cpp")
    s = open(p, encoding="utf-8").read()
    begin = s.index("\n", s.index("// BEGIN GENERATED ROSTER")) + 1
    end = s.index("\t// END GENERATED ROSTER")
    open(p, "w", encoding="utf-8").write(s[:begin] + cpp_roster() + s[end:])


