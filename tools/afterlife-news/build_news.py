# Builds every Afterlife news output from roster.py:
#   * the built-in roster of src/afterlife/AfterlifeModel.cpp (between the GENERATED ROSTER markers);
#   * lua/afterlife_news.lua, the advisor script that puts the Afterlife news in the ticker;
#   * tools/afterlife-test/reference/PACK_CONSTANTS.lua, the test fixture (roster and events only change);
#   * optionally, with --dat CONTROLLER_IN CONTROLLER_OUT LTEXT_OUT:
#       CAM_LUA_Controller.dat with the news script added (or replaced) and the LTEXT .dat of the ticker lines.
#
#   python3 tools/afterlife-news/build_news.py [--dat CAM_LUA_Controller.dat out/CAM_LUA_Controller.dat out/CAM_Afterlife_News_en.dat]
#
# Run from the repository root.
import argparse, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import roster, dbpf2

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

LUA_TYPE, LUA_GROUP = 0xCA63E2A3, 0x4A5E8EF6
NEWS_LUA_INSTANCE = 0x8BB3C100            # package signature 0BB3C100 (the old AFTERLIFE.lua range), high bit set as the pack does
LTEXT_TYPE = 0x2026960B
LTEXT_GROUP = 0x6A231EAA                  # !! must match the group the pack's other text@ strings use (see docs/afterlife.md)
ADVICE_BASE = 0xBB3C2000                  # advice GUIDs: BB3C2000 + index of the character


def cpp_roster():
    out = ["\tconstexpr NewsCharacter kCharacters[] = {"]
    for k, name, role, src, species, iid, _ in roster.CHARACTERS:
        out.append(f'\t\t{{ "{k}", "{name}", "{role}", "{src}", "{species}", "text@{iid:08X}" }},')
    out.append("\t};\n")
    for ev, ks in roster.EVENTS:
        out.append(f"\tconstexpr const char* kEvent_{ev}[] = {{ " + ", ".join(f'"{k}"' for k in ks) + " };")
    out.append("\n\tconstexpr NewsEvent kEvents[] = {")
    for ev, _ in roster.EVENTS:
        out.append(f'\t\tEvent("{ev}", kEvent_{ev}),')
    out.append("\t};")
    return "\n".join(out) + "\n"


def write_cpp():
    p = os.path.join(ROOT, "src/afterlife/AfterlifeModel.cpp")
    s = open(p, encoding="utf-8").read()
    begin = s.index("\n", s.index("// BEGIN GENERATED ROSTER")) + 1
    end = s.index("\t// END GENERATED ROSTER")
    open(p, "w", encoding="utf-8").write(s[:begin] + cpp_roster() + s[end:])


def news_lua():
    ev_lines = "\n".join(f'--   {ev:<26} {", ".join(ks)}' for ev, ks in roster.EVENTS)
    advices = []
    for n, c in enumerate(roster.CHARACTERS):
        k, name, iid = c[0], c[1], c[5]
        guid = f"{ADVICE_BASE + n:08x}"
        advices.append(f"""-- {name}
delete_advice('{guid}')
a           = create_advice_fluff('{guid}')
a.trigger   = "afterlife_news.is_pick('text@{iid:08X}')"
a.title     = [[text@{iid:08X}]]
a.priority  = tuning_constants.ADVICE_PRIORITY_LOW
a.mood      = advice_moods.FLUFF
a.frequency = afterlife_news.FREQUENCY_DAYS
a.timeout   = 30
a.news_only = 1
""")
    return f"""--#-package:0BB3C100# -- package signature --
-- Lua file entry IID 0x{NEWS_LUA_INSTANCE:08x}
-- Based on the NEON ENGINE by RobertaME / Ulisse Wolf --
-- AFTERLIFE NEWS --
-- Puts the fictitious Afterlife statistics (Winners, Sinners, I.M.P. kills, redemptions) in the news ticker.
-- GENERATED by tools/afterlife-news/build_news.py from roster.py: edit roster.py and rebuild, not this file.
--------------------------------------------------------------------------------------------------
-- NEEDS SC4SIM.dll (1.9.1 or later). The DLL registers run_afterlife_balance_variables() and
-- get_news_ticker_character() when a city opens; AFTERLIFE.lua and PACK_CONSTANTS.lua are no longer part of the
-- pack. Without the DLL this script does nothing: every trigger below stays false.
--
-- Once per game month, afterlife_news.update():
--   1. runs one Afterlife cycle (run_afterlife_balance_variables), which also fills afterlife_grid_var;
--   2. with a chance of NEWS_CHANCE %, picks an event that this month's numbers support;
--   3. asks the DLL for a character on topic for that event (get_news_ticker_character).
-- Each character has one fluff advice below, whose trigger is true only in the month that character is picked; its
-- title is the character's ticker line (LTEXT text@BB3C1000 - text@BB3C1063, CAM_Afterlife_News_en.dat).
--
-- Events and characters (built into SC4SIM.dll):
{ev_lines}
--------------------------------------------------------------------------------------------------
dofile("adv_fluffnews.lua")

afterlife_news = {{}}
afterlife_news.NEWS_CHANCE    = 50     -- % chance of an Afterlife headline in a month (game.random_chance)
afterlife_news.FREQUENCY_DAYS = 360    -- the same character's line comes back at most once a year
afterlife_news.last_month     = -1     -- game month of the last cycle
afterlife_news.pick           = nil    -- ticker_text_id picked for this month, or nil

-- Events whose condition holds this month, from the values the DLL copied into afterlife_grid_var.
function afterlife_news.candidate_events()
   local v = afterlife_grid_var
   local events = {{}}
   if (v.IMP_KILLS_THIS_CYCLE > 0)    then table.insert(events, "IMP_KILL_REPORT") end
   if (v.REDEEMED_THIS_CYCLE > 0)     then table.insert(events, "REDEMPTION_REPORT") end
   if (v.WINNER_COUNT_THIS_CYCLE > 0) then table.insert(events, "HEAVEN_REPORT") end
   if (v.NATURAL_DEATHS > 0)          then table.insert(events, "NATURAL_DEATH_REPORT") end
   if (v.SINNER_POPULATION_HELL > 0)  then
      table.insert(events, "OVERLORD_REPORT")
      table.insert(events, "SEVEN_DEADLY_SINS_REPORT")
   end
   if (v.HELL_NATIVE_TOTAL > v.FALLEN_ANGELS_POPULATION + v.SEVEN_DEADLY_SINS_POPULATION) then
      table.insert(events, "HELL_NATIVE_REPORT")
   end
   return events
end

function afterlife_news.update()
   if (run_afterlife_balance_variables == nil or get_news_ticker_character == nil) then
      return                                   -- SC4SIM.dll not loaded: no Afterlife news
   end
   local month = game.g_year * 12 + game.g_month
   if (month == afterlife_news.last_month) then
      return                                   -- already done this month
   end
   afterlife_news.last_month = month
   afterlife_news.pick = nil

   run_afterlife_balance_variables("D")
   if (afterlife_grid_var == nil or not game.random_chance(afterlife_news.NEWS_CHANCE)) then
      return
   end
   local events = afterlife_news.candidate_events()
   local count = table.getn(events)
   if (count == 0) then
      return
   end
   -- rotate through the events month by month, so one busy statistic does not take every headline
   local entry = get_news_ticker_character(events[math.mod(month, count) + 1])
   if (entry ~= nil) then
      afterlife_news.pick = entry.ticker_text_id
   end
end

-- Trigger of every Afterlife advice: true when text_id is this month's pick.
function afterlife_news.is_pick(text_id)
   afterlife_news.update()
   return afterlife_news.pick == text_id
end

{chr(10).join(advices)}"""


def write_lua():
    p = os.path.join(ROOT, "lua/afterlife_news.lua")
    open(p, "w", encoding="utf-8", newline="\n").write(news_lua())
    return p


def write_reference_constants():
    """Test fixture: the original PACK_CONSTANTS.lua with the roster and event tables of roster.py."""
    p = os.path.join(ROOT, "tools/afterlife-test/reference/PACK_CONSTANTS.lua")
    s = open(p, encoding="utf-8").read()
    w = max(len(c[0]) for c in roster.CHARACTERS)
    rows = [f'   {c[0]:<{w}} = {{ full_name = "{c[1]}", role = "{c[2]}", source = "{c[3]}", species = "{c[4]}", ticker_text_id = "text@{c[5]:08X}" }}'
            for c in roster.CHARACTERS]
    a = s.index("hell_news_characters = {\n") + len("hell_news_characters = {\n")
    s = s[:a] + ",\n".join(rows) + s[s.index("\n}", a):]
    w = max(len(e) for e, _ in roster.EVENTS)
    rows = [f'   {e:<{w}} = {{ ' + ", ".join(f'"{k}"' for k in ks) + " }" for e, ks in roster.EVENTS]
    a = s.index("news_ticker_event_characters = {\n") + len("news_ticker_event_characters = {\n")
    s = s[:a] + ",\n".join(rows) + s[s.index("\n}", a):]
    open(p, "w", encoding="utf-8").write(s)


def ltext(text):
    return struct.pack("<HH", len(text), 0x1000) + text.encode("utf-16-le")


def write_dats(controller_in, controller_out, ltext_out, lua_text):
    header, entries = dbpf2.read(controller_in)
    entries = [e for e in entries if not (e["t"] == LUA_TYPE and e["i"] == NEWS_LUA_INSTANCE)]
    entries.append(dict(t=LUA_TYPE, g=LUA_GROUP, i=NEWS_LUA_INSTANCE, data=lua_text.encode("utf-8")))
    dbpf2.write(controller_out, entries, header)
    texts = [dict(t=LTEXT_TYPE, g=LTEXT_GROUP, i=c[5], data=ltext(c[6])) for c in roster.CHARACTERS]
    dbpf2.write(ltext_out, texts, header)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dat", nargs=3, metavar=("CONTROLLER_IN", "CONTROLLER_OUT", "LTEXT_OUT"))
    args = ap.parse_args()
    write_cpp()
    lua_path = write_lua()
    write_reference_constants()
    if args.dat:
        write_dats(*args.dat, open(lua_path, encoding="utf-8").read())
    print("roster:", len(roster.CHARACTERS), "characters,", len(roster.EVENTS), "events")
